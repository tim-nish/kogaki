#!/usr/bin/env node
// The Passage intake — one command that puts a source Passage into the store (kogaki#1535,
// owner decision 2026-10-23).
//
// WHAT IT IS. The Proof Sheet's source Passages live in ONE untracked store,
// `corpus/passages/`, one file per Passage named by its slug (`<slug>.md`). The owner enters
// Passages out of the book's order, and a run record names its Leg file by path, so a
// filename never changes once written and carries no order. The order is `ORDER.md` in the
// store, one slug per line in the book's order — the only carrier of the sequence; nothing
// reads the directory listing for it. `INDEX.md` is regenerated from the order and the files
// on every intake.
//
// THE STORE FILE. Three header lines — `slug:`, `section:`, `source: not given` — a blank
// line, then the Passage text verbatim. `passageBody` strips that header; the counts are
// taken over the body alone, with the Extractor's own cuts (`legParagraphs`, `sentencesOf`).
//
// WHAT IT REFUSES, by name and before anything is written: a slug already in the store or
// the order, a `--before` slug absent from the order, and a file with no paragraph. No model
// call is made.
//
import { readFileSync, writeFileSync, existsSync, mkdirSync, renameSync } from "node:fs";
import { join, resolve, basename, extname } from "node:path";
import { pathToFileURL } from "node:url";
import { REPO } from "../workflow/run-record.mjs";
import { legParagraphs, sentencesOf } from "./extract.mjs";

export const STORE = join(REPO, "corpus", "passages");
export const ORDER_FILE = "ORDER.md";
export const INDEX_FILE = "INDEX.md";
const SLUG = /^[a-z0-9][a-z0-9_-]*$/;
const HEADER = /^slug: .*\nsection: .*\nsource: .*\n\n/;

function fail(msg) {
  process.stderr.write(`passage-intake: ${msg}\n`);
  process.exit(1);
}

// A slug from a filename: lower case, every run of other characters one `-`.
export function slugOf(path) {
  return basename(path, extname(path)).toLowerCase().replace(/[^a-z0-9_]+/g, "-").replace(/^-+|-+$/g, "");
}

export function passageFileText({ slug, section, text }) {
  const body = String(text).replace(/\s+$/, "");
  return `slug: ${slug}\nsection: ${section}\nsource: not given\n\n${body}\n`;
}

// The Passage text of a store file, its header stripped; a file with no header is all body.
export function passageBody(fileText) {
  return String(fileText).replace(HEADER, "");
}

export function passageCounts(text) {
  const paragraphs = legParagraphs(text);
  return { paragraphs: paragraphs.length, sentences: paragraphs.reduce((n, p) => n + sentencesOf(p).length, 0) };
}

export function readOrder(store) {
  const p = join(store, ORDER_FILE);
  if (!existsSync(p)) return [];
  return readFileSync(p, "utf8").split("\n").map((l) => l.trim()).filter(Boolean);
}

export function indexText(store, order) {
  const rows = order.map((slug, i) => {
    const p = join(store, `${slug}.md`);
    if (!existsSync(p)) fail(`${ORDER_FILE} names \`${slug}\`, and the store holds no ${slug}.md. Nothing was written.`);
    const c = passageCounts(passageBody(readFileSync(p, "utf8")));
    return `| ${i + 1} | ${slug} | ${c.paragraphs} | ${c.sentences} |`;
  });
  return ["# Passages", "", `Generated by src/proof-sheet/passage-intake.mjs from ${ORDER_FILE}; never edited by hand.`, "",
    "| # | slug | paragraphs | sentences |", "|---|---|---|---|", ...rows, ""].join("\n");
}

function writeAtomic(path, text) {
  writeFileSync(`${path}.tmp`, text);
  renameSync(`${path}.tmp`, path);
}

// Put one Passage into the store. Every refusal fires before the first write.
export function intake(file, { store = STORE, slug = null, before = null, section = "not given" } = {}) {
  let text;
  try { text = readFileSync(file, "utf8"); } catch (e) { fail(`the file at ${file} cannot be read (${e.message})`); }
  const s = slug || slugOf(file);
  if (!SLUG.test(s)) fail(`the slug \`${s}\` is not lower-case letters, digits, \`-\` and \`_\`; name one with --slug. Nothing was written.`);
  const order = readOrder(store);
  if (order.includes(s) || existsSync(join(store, `${s}.md`))) fail(`the slug \`${s}\` is already in the store. Nothing was written.`);
  if (before && !order.includes(before)) fail(`the --before slug \`${before}\` is not in ${ORDER_FILE}. Nothing was written.`);
  const counts = passageCounts(text);
  if (!counts.paragraphs) fail(`the file at ${file} carries no paragraph. Nothing was written.`);
  const next = before ? [...order.slice(0, order.indexOf(before)), s, ...order.slice(order.indexOf(before))] : [...order, s];
  mkdirSync(store, { recursive: true });
  writeAtomic(join(store, `${s}.md`), passageFileText({ slug: s, section, text }));
  writeAtomic(join(store, ORDER_FILE), `${next.join("\n")}\n`);
  writeAtomic(join(store, INDEX_FILE), indexText(store, next));
  return { slug: s, position: next.indexOf(s) + 1, ...counts };
}

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) { args._.push(a); continue; }
    const next = argv[i + 1];
    if (next === undefined || next.startsWith("--")) fail(`${a} takes a value`);
    args[a.slice(2)] = next;
    i++;
  }
  return args;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const usage = "usage: node src/proof-sheet/passage-intake.mjs <file> [--slug <slug>] [--before <slug>] [--section <text>] [--store <dir>]";
  const args = parseArgs(process.argv.slice(2));
  const known = new Set(["_", "slug", "before", "section", "store"]);
  const unknown = Object.keys(args).find((k) => !known.has(k));
  if (unknown) fail(`unknown flag --${unknown}\n${usage}`);
  if (args._.length !== 1) fail(usage);
  const r = intake(args._[0], { store: args.store ? resolve(args.store) : STORE, slug: args.slug || null,
    before: args.before || null, section: args.section || "not given" });
  console.log(`${r.slug}: ${r.paragraphs} paragraph(s), ${r.sentences} sentence(s), position ${r.position} in ${ORDER_FILE}`);
}
